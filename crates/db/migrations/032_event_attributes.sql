-- ============================================================
-- 事件结构化：event 表补 attributes（JSONB）
--
-- 背景（来自 AI 使用方的实际反馈，已核实）：事件此前只能写 name + description，
-- 但它天然是结构化的——「炼器神明失踪」有发生时间、地点、参与方、直接后果、
-- 揭示时机。这些信息现在只能塞进 description，于是「有几个事件发生在同一个
-- 地点」「哪些事件属于暗线」这类问题都查不了。
--
-- 为什么用 attributes 而不是逐个加列：
--   叙述性字段（直接后果 / 揭示时机 / 地点）与创作强相关、还会继续增删；
--   逐个加列要反复迁移，而 JSONB 便于演进。
--   真正需要按列过滤的字段仍然保留列（发生时间用已有的 event_time，
--   参与方用已有的 event_entity 表）。
--
-- 约定（由 create_event 工具写入）：
--   {
--     "where":         "地点叙述（如 全世界 / 阴面·轮回渡）",
--     "participants":  [{"entity_id": "...", "name": "炼器神明", "role": "失踪者"}],
--     "consequences":  "直接后果",
--     "reveal_at":     "揭示时机（如 前期不透 / 第二卷）"
--   }
--
-- 幂等，可重复执行。
-- ============================================================

ALTER TABLE event
    ADD COLUMN IF NOT EXISTS attributes JSONB NOT NULL DEFAULT '{}'::jsonb;
