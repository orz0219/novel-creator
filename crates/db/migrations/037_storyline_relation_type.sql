-- ============================================================
-- 剧情线之间的关系类型：relation_type
--
-- 背景（来自 AI 使用方反馈，已核实）：副线正文里反复写着「《破庙居委会》吃得越多 →
-- 《现实线的建设》压力越大」「与《旧秩序的墙》在神迹外传上对接」——这些是**有向的
-- 依赖 / 驱动 / 交汇 / 对冲**，但 storyline_relation 只有 parent_id / child_id，
-- 只能表达一棵"挂载树"，横向关系无处可写，前端也画不出"线咬合图"。
--
-- 做法：加 relation_type（枚举），列名保持 parent_id / child_id 不动
-- （改列名要动前端与全部读写路径，收益不匹配）；建边工具对外用
-- from / to 的中性说法，落库映射到这两列。
--
-- 默认 'Contains'：既有的 6 条边都是「主线-支线」的挂载关系，语义上正是"包含"。
--
-- 幂等，可重复执行。
-- ============================================================

ALTER TABLE storyline_relation
    ADD COLUMN IF NOT EXISTS relation_type VARCHAR NOT NULL DEFAULT 'Contains';
