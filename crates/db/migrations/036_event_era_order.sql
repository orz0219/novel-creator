-- ============================================================
-- 事件的历史轴排序锚：era_order
--
-- 背景（来自 AI 使用方反馈，已核实）：`event.when` 是自由文本（「远昔」「缓变」），
-- 中文没法比大小，历史轴一定排乱——「千年之前」和「第三卷」谁在前，SQL 排不出来。
--
-- 做法：**不动 when**（它给人看，保留叙述性），另加一个数值锚 era_order
-- （越小越早；NULL = 未标定）。列表默认仍按创建时间倒序（「最近发生了什么」），
-- 想看历史轴时传 order_by="era" 按这个锚排。
--
-- 幂等，可重复执行。
-- ============================================================

ALTER TABLE event ADD COLUMN IF NOT EXISTS era_order INTEGER;
